-- Thêm từ bằng giọng nói (Prompt 2.5): đếm lượt nhận dạng giọng nói qua máy chủ (Azure Speech)
-- và lượt tra ngược bằng AI; tìm từ trong kho theo nghĩa tiếng Việt (tra ngược miễn phí).

create extension if not exists unaccent with schema extensions;

/* ---------- Giới hạn lượt dùng có chi phí ---------- */

insert into private.settings (key, value, note) values
  ('user_daily_transcribe', 100, 'Số lần nhận dạng giọng nói qua máy chủ mỗi người mỗi ngày'),
  ('user_daily_reverse_ai', 30, 'Số lần tra ngược (tiếng Việt → tiếng Anh) bằng AI mỗi người mỗi ngày')
on conflict (key) do nothing;

create table public.usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null check (kind in ('transcribe', 'reverse_ai')),
  created_at timestamptz not null default now()
);

comment on table public.usage_events is
  'Lượt dùng tính phí theo người (giới hạn mỗi ngày). Không lưu nội dung giọng nói hay câu tra.';

create index usage_events_user_day_idx on public.usage_events (user_id, kind, created_at);

alter table public.usage_events enable row level security;

create policy "usage_events: đọc của mình"
  on public.usage_events for select to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.usage_events from anon;
revoke insert, update, delete, truncate on public.usage_events from authenticated;

-- Trừ một lượt nếu còn (khóa theo người để hai yêu cầu song song không cùng lọt).
-- Trả về { allowed, remaining, daily_limit }. Chỉ service role (Edge Function) gọi.
create function public.consume_usage(p_user_id uuid, p_kind text)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_limit integer := private.setting('user_daily_' || p_kind);
  v_used integer;
begin
  if v_limit is null then
    raise exception 'không có giới hạn cho %', p_kind using errcode = '22023';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('usage:' || p_user_id::text || ':' || p_kind, 0));
  select count(*) into v_used from public.usage_events
  where user_id = p_user_id and kind = p_kind and created_at >= private.vn_day_start();
  if v_used >= v_limit then
    return jsonb_build_object('allowed', false, 'remaining', 0, 'daily_limit', v_limit);
  end if;
  insert into public.usage_events (user_id, kind) values (p_user_id, p_kind);
  return jsonb_build_object('allowed', true, 'remaining', v_limit - v_used - 1, 'daily_limit', v_limit);
end;
$$;

revoke all on function public.consume_usage(uuid, text) from public, anon, authenticated;
grant execute on function public.consume_usage(uuid, text) to service_role;

/* ---------- Tra ngược trong kho theo nghĩa tiếng Việt ---------- */

-- "kiên cường" (có dấu hay không) → các từ có nghĩa chứa cụm đó như một cụm từ trọn vẹn.
-- Khớp đúng dấu xếp trước, rồi nghĩa bắt đầu bằng cụm tra, rồi theo độ thông dụng. Ai cũng gọi được (miễn phí).
create function public.search_by_meaning(p_query text, p_language text default 'en', p_limit integer default 5)
returns jsonb
language sql
stable
set search_path = ''
as $$
  with q as (
    select
      btrim(regexp_replace(
        lower(extensions.unaccent(coalesce(p_query, ''))), '[^a-z0-9]+', ' ', 'g')) as term,
      lower(btrim(coalesce(p_query, ''))) as raw
  ),
  matched as (
    select distinct on (w.id)
      w.id as word_id, w.lemma, w.pos, w.frequency_rank, s.id as sense_id, s.meaning_vi,
      (regexp_replace(lower(extensions.unaccent(s.meaning_vi)), '[^a-z0-9]+', ' ', 'g')
        like q.term || '%') as starts,
      -- Khớp đúng cả dấu ("chạy" không lẫn "cháy") xếp trước.
      (position(q.raw in lower(s.meaning_vi)) > 0) as exact
    from public.word_senses s
    join public.words w on w.id = s.word_id, q
    where char_length(q.term) between 2 and 60
      and w.language = p_language
      and not w.is_hidden
      and (' ' || regexp_replace(lower(extensions.unaccent(s.meaning_vi)), '[^a-z0-9]+', ' ', 'g') || ' ')
        like '% ' || q.term || ' %'
    order by w.id, s.sense_order
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'wordId', m.word_id, 'lemma', m.lemma, 'pos', m.pos, 'senseId', m.sense_id,
    'meaning', m.meaning_vi
  ) order by m.exact desc, m.starts desc, m.frequency_rank nulls last, m.lemma), '[]'::jsonb)
  from (
    select * from matched
    order by exact desc, starts desc, frequency_rank nulls last, lemma
    limit least(greatest(p_limit, 1), 10)
  ) m;
$$;

grant execute on function public.search_by_meaning(text, text, integer) to anon, authenticated;
